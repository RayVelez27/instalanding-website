import { useEffect, useLayoutEffect, useMemo, useRef, useState, type CSSProperties } from "react";
import { Link, useLocation, useNavigate } from "react-router-dom";
import { ArrowRight, ArrowUpRight, Check, Copy, Search } from "lucide-react";
import { ICON_ITEMS, MOTION_ITEMS, PAGE_ITEMS, PRODUCT_ITEMS, SYSTEM_ITEMS, VIDEO_ITEMS, type Item } from "@/lib/libraryItems";
import { agentPrompt } from "@/lib/openWith";
import { HERO_FONTS } from "@/data/heroFonts";
import { HERO_ACCENTS } from "@/data/heroAccents";
import type { SheetKind } from "@/components/ItemSheet";
import { copyText } from "@/lib/copyText";
import { track } from "@/lib/track";

/**
 * The HOME hero: "Give Your Agent Taste", on two lines. On the left, describe what you
 * want; on the right, the best match, live as you type, one per category:
 * a landing page first, and Next steps through motion, systems, videos,
 * products and icons (then back to pages), each the best match for the same
 * words. Preview / HTML shows the item or its file; Copy for agent copies the
 * item's agent prompt; Find a design opens the item showing. Before anyone
 * types, it matches the placeholder, so the hero always shows a real answer.
 *
 * Matching is keywords only: filler words dropped, any remaining word can
 * match an item's title, description, tags and uses; title hits count most,
 * words nearly everything has count a quarter, and "dark" or "light" picks
 * the theme. A category with no hit shows its newest item.
 *
 * The left side wears the match's font pairing: its headline font (family,
 * weight, style, tracking) on the headline and its body font
 * on the line, the box and the buttons under it, read from each item's own
 * file (data/heroFonts.ts, regenerated by scripts/hero-fonts). The fonts load
 * the first time they are needed; the headline shrinks if a wide face would
 * overflow its column. The accent (the headline's last word, Find, the tabs,
 * Copy for agent) takes the match's own colour (data/heroAccents.ts), and the
 * last word changes per category, letter by letter: Taste, Moves, Style,
 * Flair, Tools, Icons.
 *
 * Next has a short loading beat: the next design's picture and fonts load
 * first (a line sweeps across the top, the picture dims under a shimmer, the
 * words soften), then everything changes at once, so a switch from one design
 * to another never shows a half-loaded picture or a fallback font. At least
 * ~a third of a second so it reads as intended, at most 1.5s on a slow line.
 */
const PLACEHOLDER = "A dark landing page for an AI finance app";
const FILLER = new Set(
  "a an the and or for of to in on with my our your me we i it is that this like build make want need some something page site website landing one design".split(" "),
);
const THEMES = new Set(["dark", "light"]);
/** Words nearly every item has: they still count, a quarter as much */
const COMMON = new Set(["ai", "app", "agent", "agents", "product", "startup"]);
const terms = (q: string) =>
  q
    .toLowerCase()
    .split(/[^a-z0-9]+/)
    .filter((t) => t.length > 1 && !FILLER.has(t));

const best = (items: readonly Item[], q: string): Item | undefined => {
  const ts = terms(q);
  if (!ts.length) return undefined;
  let hit: Item | undefined;
  let top = 0;
  for (const it of items) {
    const title = it.title.toLowerCase();
    // "dark" / "light" asks for the theme: only the theme counts, and the wrong one counts against
    const score = ts.reduce(
      (n, t) =>
        n +
        (THEMES.has(t)
          ? t === it.theme ? 5 : -5
          : (title.includes(t) ? 3 : it.words.includes(t) ? 1 : 0) * (COMMON.has(t) ? 0.25 : 1)),
      0,
    );
    if (score > top) {
      top = score;
      hit = it;
    }
  }
  return hit;
};

type Cat = { kind: SheetKind; label: string; word: string; items: readonly Item[] };
/** The categories Next steps through, in order, and the word each puts in the headline (five letters each) */
const CATS: Cat[] = (
  [
    { kind: "page", label: "Landing page", word: "Taste", items: PAGE_ITEMS },
    { kind: "motion", label: "Motion study", word: "Moves", items: MOTION_ITEMS },
    { kind: "system", label: "Design system", word: "Style", items: SYSTEM_ITEMS },
    { kind: "video", label: "Video", word: "Flair", items: VIDEO_ITEMS },
    { kind: "product", label: "Product", word: "Tools", items: PRODUCT_ITEMS },
    { kind: "icons", label: "Icon set", word: "Icons", items: ICON_ITEMS },
  ] as Cat[]
).filter((c) => c.items.length > 0);

/** One match per category for the words (the placeholder's when empty, else the newest) */
const matchAll = (q: string) =>
  CATS.map((c) => best(c.items, q || PLACEHOLDER) ?? best(c.items, PLACEHOLDER) ?? c.items[0]);

const slugOf = (it: Item) => it.to.split("/").pop() ?? "";
const LIME = "#e4ff3a";

/**
 * The headline's last word. A new word rolls in letter by letter (each one
 * flips up out of a blur, a beat after the one before) while the old one
 * flips away above it; both share one grid cell, so the line never jumps.
 */
const WordSwap = ({ word }: { word: string }) => {
  const [shown, setShown] = useState({ cur: word, prev: null as string | null, n: 0 });
  useEffect(() => {
    setShown((s) => (s.cur === word ? s : { cur: word, prev: s.cur, n: s.n + 1 }));
  }, [word]);
  useEffect(() => {
    if (!shown.prev) return;
    const t = window.setTimeout(() => setShown((s) => ({ ...s, prev: null })), 1100);
    return () => window.clearTimeout(t);
  }, [shown.prev, shown.n]);
  const letters = (w: string) =>
    [...w].map((ch, i) => (
      <span key={i} style={{ "--i": i } as CSSProperties}>
        {ch}
      </span>
    ));
  return (
    <span className="hh-swap">
      {shown.prev && (
        <span key={`out-${shown.n}`} className="hh-swap-w is-out" aria-hidden="true">
          {letters(shown.prev)}
        </span>
      )}
      <span key={`in-${shown.n}`} className={`hh-swap-w${shown.n ? " is-in" : ""}`}>
        {letters(shown.cur)}
      </span>
    </span>
  );
};

const SITE_DISPLAY = "'Inter Tight', 'Inter', system-ui, sans-serif";
const loaded = new Set<string>();
/** Adds a Google Fonts stylesheet once */
const loadSheet = (href: string) => {
  if (loaded.has(href)) return;
  loaded.add(href);
  const l = document.createElement("link");
  l.rel = "stylesheet";
  l.href = href;
  l.dataset.heroFont = "";
  document.head.appendChild(l);
};
const wait = (ms: number) => new Promise((r) => window.setTimeout(r, ms));
/** Loads an item's picture and fonts; resolves when they are ready (or after 1.5s regardless) */
const prepare = async (it: Item) => {
  const f = HERO_FONTS[it.key];
  f?.href?.forEach(loadSheet);
  const img = new Image();
  img.src = it.image;
  const jobs: Promise<unknown>[] = [img.decode().catch(() => undefined)];
  if (f && document.fonts) {
    jobs.push(
      document.fonts.load(`${f.di ? "italic " : ""}${f.dw} 64px ${f.d}`).catch(() => undefined),
      document.fonts.load(`400 16px ${f.b}`).catch(() => undefined),
    );
  }
  await Promise.race([Promise.all(jobs), wait(1500)]);
};

/** The match's pairing as CSS variables on the left column */
const pairing = (key: string): CSSProperties => {
  const f = HERO_FONTS[key];
  if (!f) return {};
  return {
    "--hh-display": `${f.d}, ${SITE_DISPLAY}`,
    "--hh-dw": f.dw,
    "--hh-ds": f.di ? "italic" : "normal",
    "--hh-ls": `${f.ls}em`,
    "--hh-body": `${f.b}, ${SITE_DISPLAY}`,
  } as CSSProperties;
};
const htmlCache = new Map<string, string>();

const HomeHero = () => {
  const navigate = useNavigate();
  const location = useLocation();
  const [q, setQ] = useState("");
  const [typed, setTyped] = useState(""); // q, a beat after the last key
  const [cat, setCat] = useState(0);
  const [loading, setLoading] = useState(false);
  const [view, setView] = useState<"preview" | "html">("preview");
  const [html, setHtml] = useState("");
  const [copied, setCopied] = useState(false);
  const copyTimer = useRef<number>();
  useEffect(() => () => window.clearTimeout(copyTimer.current), []);

  useEffect(() => {
    const t = window.setTimeout(() => setTyped(q), 160);
    return () => window.clearTimeout(t);
  }, [q]);

  const matches = useMemo(() => matchAll(typed), [typed]);
  const { kind, label, word } = CATS[cat];
  const match = matches[cat];
  const next = CATS[(cat + 1) % CATS.length];
  const slug = slugOf(match);
  const state = kind === "page" ? { backgroundLocation: location } : undefined;

  // Load the match's fonts, then fit the headline to its column
  const title = useRef<HTMLHeadingElement>(null);
  useEffect(() => {
    HERO_FONTS[match.key]?.href?.forEach(loadSheet);
  }, [match.key]);
  useLayoutEffect(() => {
    const h = title.current;
    if (!h) return;
    let live = true;
    const measure = () => {
      if (!live) return;
      // Measure at full size, then shrink so the widest line fits
      h.style.setProperty("--hh-fit", "1");
      const lines = [...h.children] as HTMLElement[];
      const widest = Math.max(...lines.map((l) => l.offsetWidth));
      const k = widest > h.clientWidth ? h.clientWidth / widest : 1;
      h.style.setProperty("--hh-fit", String(Math.max(0.5, Math.floor(k * 100) / 100)));
    };
    measure();
    const f = window.requestAnimationFrame(() => window.requestAnimationFrame(measure)); // once the new word has rendered
    document.fonts?.ready.then(measure);
    const t = window.setTimeout(measure, 1200); // a stylesheet that just arrived, a word that just landed
    window.addEventListener("resize", measure);
    return () => {
      live = false;
      window.clearTimeout(t);
      window.cancelAnimationFrame(f);
      window.removeEventListener("resize", measure);
    };
  }, [match.key, word]);

  // The HTML tab reads the file itself, once per file
  useEffect(() => {
    if (view !== "html" || !match.code) return;
    const hit = htmlCache.get(match.code);
    if (hit) return setHtml(hit);
    setHtml("");
    let live = true;
    fetch(match.code)
      .then((r) => r.text())
      .then((text) => {
        htmlCache.set(match.code, text);
        if (live) setHtml(text);
      })
      .catch(() => undefined);
    return () => {
      live = false;
    };
  }, [view, match.code]);

  const open = () => {
    track("home_hero_find", { kind, slug, typed: q ? "yes" : "no" });
    navigate(match.to, { state });
  };

  const copyForAgent = async () => {
    await copyText(agentPrompt(kind, slug, match.title));
    track("open_with", { agent: "copy", kind, slug, from: "home_hero" });
    setCopied(true);
    window.clearTimeout(copyTimer.current);
    copyTimer.current = window.setTimeout(() => setCopied(false), 1600);
  };

  const goNext = async () => {
    if (loading) return;
    const n = (cat + 1) % CATS.length;
    track("home_hero_next", { kind: CATS[n].kind });
    setCopied(false);
    const still = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    setLoading(true);
    await Promise.all([prepare(matches[n]), wait(still ? 0 : 380)]);
    setCat(n);
    setLoading(false);
  };

  return (
    <section
      className={`hh${loading ? " is-loading" : ""}`}
      aria-labelledby="home-title"
      aria-busy={loading}
      style={{ "--hh-accent": HERO_ACCENTS[match.key] ?? LIME } as CSSProperties}
    >
      <span className="hh-load" aria-hidden="true" />
      <div className="hh-l" style={pairing(match.key)}>
        <h1 id="home-title" className="hh-title" ref={title}>
          <span>Give Your</span>
          <span>
            Agent{" "}
            <em>
              <WordSwap word={word} />
            </em>
          </span>
        </h1>
        <p className="hh-sub">Find a design. Ship it as a single HTML file.</p>
        <form
          className="hh-ask"
          role="search"
          onSubmit={(e) => {
            e.preventDefault();
            open();
          }}
        >
          <Search size={20} aria-hidden="true" />
          <input
            type="search"
            value={q}
            onChange={(e) => setQ(e.target.value)}
            placeholder={PLACEHOLDER}
            aria-label="Describe what you want"
            aria-describedby="hh-match"
            enterKeyHint="search"
            autoComplete="off"
          />
          <button type="submit" className="hh-go">
            Find<span className="hh-go-more">&nbsp;a design</span>
            <ArrowRight size={18} aria-hidden="true" />
          </button>
        </form>
        <Link to="/agents#agents-ways" className="hh-mcp">
          Connect via MCP <ArrowUpRight size={17} aria-hidden="true" />
        </Link>
      </div>

      <div className="hh-r">
        <div className="hh-r-head">
          <p id="hh-match" className="hh-r-label" aria-live="polite">
            <span>Matched design</span>
            <span className="hh-r-cat">
              {label} · {cat + 1}/{CATS.length}
            </span>
            <span className="hh-sr"> : {match.title}</span>
          </p>
          <div className="hh-tabs" role="tablist" aria-label="Show the design as">
            {(["preview", "html"] as const).map((v) => (
              <button
                key={v}
                type="button"
                role="tab"
                aria-selected={view === v}
                className={view === v ? "is-on" : undefined}
                onClick={() => setView(v)}
              >
                {v === "preview" ? "Preview" : "HTML"}
              </button>
            ))}
          </div>
        </div>

        <div className="hh-card">
          <div className="hh-card-in">
            {view === "preview" ? (
              <Link to={match.to} state={state} className="hh-shot" aria-label={`Open ${match.title}`}>
                <img key={match.key} src={match.image} alt="" width={1200} height={600} decoding="async" />
              </Link>
            ) : (
              <pre className="hh-code" tabIndex={0} aria-label={`The HTML of ${match.title}`}>
                {html ? html.split("\n").slice(0, 160).join("\n") : "Loading the file…"}
              </pre>
            )}
          </div>
        </div>

        <div className="hh-foot">
          <span className="hh-brand" title={match.title}>
            {match.title}
          </span>
          <button type="button" className="hh-btn hh-btn--hot" onClick={copyForAgent}>
            {copied ? <Check size={20} aria-hidden="true" /> : <Copy size={20} aria-hidden="true" />}
            {copied ? "Copied" : "Copy for agent"}
          </button>
          <button
            type="button"
            className="hh-btn"
            onClick={goNext}
            aria-disabled={loading}
            aria-label={`Next: ${next.label.toLowerCase()}`}
          >
            Next
            <ArrowRight size={20} aria-hidden="true" />
          </button>
        </div>
      </div>
    </section>
  );
};

export default HomeHero;
